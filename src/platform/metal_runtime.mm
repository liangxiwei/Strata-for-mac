id<MTLDevice> g_device;
id<MTLLibrary> g_library;
std::string g_code_error = "kernel library not loaded yet";
std::map<std::string, id<MTLComputePipelineState>> g_pso;
std::map<const void*, std::string> g_pso_names;      // pipeline -> kernel name, for the diagnostic profile

struct Range {
    const void* base;
    size_t bytes;
    id<MTLBuffer> buffer;
};
std::map<const void*, Range> g_ranges;                // keyed by base; lookups resolve interiors

struct TapeEntry {
    id<MTLComputePipelineState> pso = nil;
    MTLSize grid = {0, 0, 0}, block = {0, 0, 0};
    NSUInteger shared_bytes = 0;
    // a memcpy entry: pso == nil, the two buffers and the byte count (the engine's graphs carry memcpy nodes)
    bool is_copy = false;
    id<MTLBuffer> copy_dst = nil, copy_src = nil;
    NSUInteger copy_dst_off = 0, copy_src_off = 0, copy_bytes = 0;
    struct Arg {
        id<MTLBuffer> buffer = nil;                    // nil for a by-value arg (an uninitialised id is NOT nil)
        bool is_null = false;                          // a genuinely-null pointer argument (bound as nil)
        NSUInteger offset = 0, bytes = 0;
        std::vector<unsigned char> value;              // by-value payload (capture bakes it, as CUDA does)
    };
    std::vector<Arg> args;
};

struct Tape {
    std::vector<TapeEntry> entries;
};

struct Stream {
    id<MTLCommandQueue> queue = nil;
    id<MTLCommandBuffer> cur = nil;
    id<MTLComputeCommandEncoder> encoder = nil;
    id<MTLCommandBuffer> inflight = nil;   // the last COMMITTED cb, retained: query is NotReady until it completes
    dispatch_queue_t callbacks;                        // serial; runs event signals and host funcs in order
    Tape* capturing = nullptr;
    bool nonblocking = false;                         // excluded from synchronous legacy-stream copies
    // STRATA_METAL_KPROFILE, direct (uncaptured) launches: the open command buffer's sample buffer and the
    // kernel of each sampled pass, resolved when that command buffer completes
    id<MTLCounterSampleBuffer> kp_samples = nil;
    std::vector<std::string>* kp_names = nullptr;
    ~Stream() { if (capturing) delete capturing; }
};

struct Event {
    id<MTLCommandBuffer> buffer = nil;
    double at_ns = 0.0;
    ~Event() { [buffer release]; }
};

std::mutex g_mu;
std::vector<Stream*> g_streams;

double now_ns() {
    return std::chrono::duration<double, std::nano>(std::chrono::steady_clock::now().time_since_epoch()).count();
}

void boot() {
    @autoreleasepool {
        static std::once_flag once;
        std::call_once(once, [] {
            g_device = MTLCreateSystemDefaultDevice();
            if (g_device == nil) {
                g_code_error = "no Metal device on this Mac";
                return;
            }
            NSError* err = nil;
            void* bytes = std::malloc(strata_metallib_size);      // DISPATCH_DATA_DESTRUCTOR_DEFAULT frees it
            std::memcpy(bytes, strata_metallib_data, strata_metallib_size);
            dispatch_data_t data = dispatch_data_create(bytes, strata_metallib_size, NULL,
                                                        DISPATCH_DATA_DESTRUCTOR_DEFAULT);
            g_library = [g_device newLibraryWithData:data error:&err];
            dispatch_release(data);
            if (g_library == nil) {
                g_code_error = std::string("newLibraryWithData: ") +
                               (err ? err.localizedDescription.UTF8String : "unknown error");
                return;
            }
            g_code_error = "ok";
        });
    }
}

/// The engine's first CUDA call can be an allocation, not a device query: every entry point lands here.
void ensure_boot() { if (g_device == nil && g_code_error == "kernel library not loaded yet") boot(); }

id<MTLComputePipelineState> pso(const char* kernel) {
    std::lock_guard<std::mutex> lock(g_mu);
    ensure_boot();
    const std::string name(kernel);
    if (const auto it = g_pso.find(name); it != g_pso.end()) return it->second;
    NSError* err = nil;
    id<MTLFunction> f = [g_library newFunctionWithName:@(kernel)];
    if (f == nil) {
        std::fprintf(stderr, "strata-metal: no kernel named '%s' in the library\n", kernel);
        std::abort();
    }
    id<MTLComputePipelineState> p = [g_device newComputePipelineStateWithFunction:f error:&err];
    [f release];
    if (p == nil) {
        std::fprintf(stderr, "strata-metal: pipeline '%s': %s\n", kernel,
                     err ? err.localizedDescription.UTF8String : "unknown error");
        std::abort();
    }
    g_pso.emplace(name, p);
    g_pso_names.emplace((const void*) p, name);
    return p;
}

Stream* as_stream(cudaStream_t s) {
    if (s == nullptr) {                                 // the default stream: one implicit serial stream
        static Stream* def = nullptr;
        if (def == nullptr) {
            def = new Stream;
            def->queue = [g_device newCommandQueue];
            if (std::getenv("STRATA_METAL_DEBUG"))
                std::fprintf(stderr, "default stream created: device=%p queue=%p\n", (void*) g_device,
                             (void*) def->queue);
            def->callbacks = dispatch_queue_create("strata.default", DISPATCH_QUEUE_SERIAL);
            std::lock_guard<std::mutex> lock(g_mu);
            g_streams.push_back(def);
        }
        return def;
    }
    return (Stream*) s;
}

void end_compute(Stream* s) {
    if (s->encoder == nil) return;
    [s->encoder endEncoding];
    [s->encoder release];
    s->encoder = nil;
}

void attach_cb_timing(id<MTLCommandBuffer> cb);
bool cb_timing();

void kprofile_direct_attach(Stream* s);

void commit_current(Stream* s) {
    if (s->cur == nil) return;
    end_compute(s);
    if (cb_timing()) attach_cb_timing(s->cur);
    if (s->kp_samples != nil) kprofile_direct_attach(s);
    [s->cur commit];
    if (s->inflight != nil) [s->inflight release];
    s->inflight = s->cur;                               // the queue's own retain keeps it executable
    s->cur = nil;
}

id<MTLCommandBuffer> ensure_cb(Stream* s) {
    if (s->cur == nil) {
        s->cur = [s->queue commandBuffer];
        [s->cur retain];
    }
    return s->cur;
}

id<MTLComputeCommandEncoder> ensure_compute(Stream* s) {
    if (s->encoder == nil) {
        // A serial compute pass orders dependent dispatches without making one pass per kernel.
        s->encoder = [ensure_cb(s) computeCommandEncoder];
        [s->encoder retain];
    }
    return s->encoder;
}

void drain(Stream* s) {
    if (s->capturing != nullptr) return;
    commit_current(s);
    id<MTLCommandBuffer> cb = s->inflight;
    if (cb == nil) return;
    // An event may already have committed the work. Waiting only on cur then returns too early.
    [cb waitUntilCompleted];
    if (std::getenv("STRATA_METAL_DEBUG"))
        std::fprintf(stderr, "drain %p: cb=%p status=%ld err=%p\n", (void*) s, (void*) cb, (long) cb.status,
                     (void*) cb.error);
    if (cb.error != nil)
        std::fprintf(stderr, "strata-metal: command buffer failed: %s\n", cb.error.localizedDescription.UTF8String);
}

void sync_stream(Stream* s) {
    if (s->capturing) return;                           // a capture records; it does not execute
    commit_current(s);
}

bool resolve(const void* ptr, id<MTLBuffer>* buffer, NSUInteger* offset) {
    std::lock_guard<std::mutex> lock(g_mu);
    if (g_ranges.empty()) return false;
    auto it = g_ranges.upper_bound(ptr);
    if (it == g_ranges.begin()) return false;
    --it;
    const Range& r = it->second;
    const char* p = (const char*) ptr;
    if (p >= (const char*) r.base + r.bytes) return false;
    *buffer = r.buffer;
    *offset = NSUInteger(p - (const char*) r.base);
    return true;
}

/// Debug: the registry's contents (for STRATA_METAL_DEBUG traces). */
void dump_ranges(const char* why) {
    std::lock_guard<std::mutex> lock(g_mu);
    std::fprintf(stderr, "ranges (%s):", why);
    for (const auto& [base, r] : g_ranges)
        std::fprintf(stderr, " [%p..%p buf=%p]", base, (const char*) base + r.bytes, (void*) r.buffer);
    std::fprintf(stderr, "\n");
}

// read once: a token replays ~1,900 entries, and getenv walks the environment on every call
bool debug_trace() {
    static const bool on = std::getenv("STRATA_METAL_DEBUG") != nullptr;
    return on;
}
bool encoder_per_kernel() {
    static const bool on = std::getenv("STRATA_METAL_ENCODER_PER_KERNEL") != nullptr;
    return on;
}

void encode_entry(id<MTLComputeCommandEncoder> enc, const TapeEntry& e) {
    [enc setComputePipelineState:e.pso];
    int i = 0;
    if (debug_trace()) {
        std::fprintf(stderr, "  encode:");
        for (const TapeEntry::Arg& a : e.args)
            std::fprintf(stderr, a.buffer != nil ? " [%llu+%llu=%p]" : " [val%zu]",
                         (unsigned long long) a.buffer.length, (unsigned long long) a.offset,
                         a.buffer != nil ? a.buffer.contents : nullptr);
        std::fprintf(stderr, "\n");
    }
    for (const TapeEntry::Arg& a : e.args) {
        if (a.is_null) [enc setBuffer:nil offset:0 atIndex:i];
        else if (a.buffer != nil) [enc setBuffer:a.buffer offset:a.offset atIndex:i];
        else [enc setBytes:a.value.data() length:a.value.size() atIndex:i];
        ++i;
    }
    if (e.shared_bytes > 0) [enc setThreadgroupMemoryLength:e.shared_bytes atIndex:0];
    [enc dispatchThreadgroups:e.grid threadsPerThreadgroup:e.block];
}

bool compute_copies() {
    static const bool enabled = [] {
        const char* v = std::getenv("STRATA_METAL_COMPUTE_COPY");
        return !v || std::atoi(v) != 0;
    }();
    return enabled;
}

/// A memcpy as a REAL stream operation inside the stream's command buffer, so ordering and
/// hazard tracking are the GPU's, exactly like cudaMemcpyAsync on a CUDA stream.  This matters because a CPU
/// memcpy into a shared buffer is NOT guaranteed visible to a kernel that follows (measured: the M1 smoke's
/// reset case - the kernel read the line before the CPU's write had become GPU-visible; the blit path sees
/// the CPU's write because blit reads go through the same tracked buffer).
bool compute_copy_fits(NSUInteger bytes) { return compute_copies() && bytes <= 65536; }

void encode_compute_copy(id<MTLComputeCommandEncoder> enc, id<MTLBuffer> db, NSUInteger doff, id<MTLBuffer> sb,
                         NSUInteger soff, NSUInteger bytes) {
    const bool vector = ((doff | soff | bytes) & 15) == 0;
    const unsigned long n = bytes / (vector ? 16 : 1);
    const unsigned threads = n <= 32 ? 32 : 128;
    static id<MTLComputePipelineState> v16 = pso("runtime_copy16"), v1 = pso("runtime_copy1");
    [enc setComputePipelineState:vector ? v16 : v1];
    [enc setBuffer:db offset:doff atIndex:0];
    [enc setBuffer:sb offset:soff atIndex:1];
    [enc setBytes:&n length:sizeof(n) atIndex:2];
    [enc dispatchThreadgroups:MTLSizeMake((n + threads - 1) / threads, 1, 1)
          threadsPerThreadgroup:MTLSizeMake(threads, 1, 1)];
}

void encode_copy_on(Stream* s, id<MTLBuffer> db, NSUInteger doff, id<MTLBuffer> sb, NSUInteger soff,
                    NSUInteger bytes) {
    if (bytes == 0) return;
    // Avoid ending/restarting the serial compute pass for doorbells, scratch and state copies.
    // Large transfers still use the blit engine. Shared host sources remain live until stream flush.
    if (compute_copy_fits(bytes)) {
        encode_compute_copy(ensure_compute(s), db, doff, sb, soff, bytes);
        return;
    }
    end_compute(s);
    id<MTLBlitCommandEncoder> b = [ensure_cb(s) blitCommandEncoder];
    [b copyFromBuffer:sb sourceOffset:soff toBuffer:db destinationOffset:doff size:bytes];
    [b endEncoding];
}

// ---- diagnostics: order-preserving GPU timing ---------------------------------------------
// STRATA_METAL_CB_TIMING=1: each committed command buffer's GPU start/end, summed into a busy/span ratio on
// stderr (no encoding change). STRATA_METAL_KPROFILE=<csv>: every replayed tape entry gets its own compute (or
// blit) pass with stage-boundary timestamps (this GPU has no dispatch-boundary sampling). Both only attach to
// the command buffers the stream already builds: nothing is committed earlier, so the mapped-source late-write
// contract is untouched. Per-pass boundaries add GPU time; KPROFILE numbers are relative, not throughput.
// Timestamps are taken as nanoseconds: on the M2 Max sampleTimestamps advances GPU and CPU (ns) clocks equally.
bool cb_timing() {
    static const bool on = std::getenv("STRATA_METAL_CB_TIMING") != nullptr;
    return on;
}

struct CbTiming {
    std::mutex mu;
    double busy_s = 0, span_s = 0, first_start = 0, last_end = 0;
    unsigned long n = 0;
};
CbTiming g_cbt;

void attach_cb_timing(id<MTLCommandBuffer> cb) {
    [cb addCompletedHandler:^(id<MTLCommandBuffer> done) {
        const double a = done.GPUStartTime, b = done.GPUEndTime;
        if (a <= 0 || b <= a) return;
        std::lock_guard<std::mutex> lock(g_cbt.mu);
        if (g_cbt.n == 0) g_cbt.first_start = a;
        g_cbt.busy_s += b - a;
        g_cbt.last_end = b;
        if (++g_cbt.n % 256 == 0) {
            const double span = g_cbt.last_end - g_cbt.first_start;
            std::fprintf(stderr, "metal cb timing: %lu cbs, GPU busy %.1f ms of %.1f ms (%.1f%%), %.3f ms/cb\n",
                         g_cbt.n, g_cbt.busy_s * 1e3, span * 1e3, span > 0 ? 100.0 * g_cbt.busy_s / span : 0.0,
                         g_cbt.busy_s * 1e3 / (double) g_cbt.n);
            g_cbt.n = 0;
            g_cbt.busy_s = 0;
        }
    }];
}

const char* kprofile_path() {
    static const char* p = std::getenv("STRATA_METAL_KPROFILE");
    return p;
}

struct KStat {
    std::string name;
    MTLSize grid = {0, 0, 0}, block = {0, 0, 0};
    double sum_ns = 0, sq_ns = 0, gap_ns = 0;
    unsigned long n = 0;
};

struct KTape {
    std::vector<KStat> e;
    unsigned long launches = 0, measured = 0;
    double span_ns = 0, busy_ns = 0;
};

std::mutex g_kmu;
std::map<const void*, KTape> g_ktapes;

void kprofile_write() {   // caller holds g_kmu
    const std::string tmp = std::string(kprofile_path()) + ".tmp";
    std::FILE* f = std::fopen(tmp.c_str(), "w");
    if (f == nullptr) return;
    std::fprintf(f, "tape,entries,launches,entry,kernel,grid_x,grid_y,grid_z,threads,mean_us,sd_us,gap_us\n");
    for (const auto& [key, t] : g_ktapes) {
        for (size_t i = 0; i < t.e.size(); ++i) {
            const KStat& k = t.e[i];
            if (k.n == 0) continue;
            const double m = k.sum_ns / (double) k.n;
            const double v = std::max(0.0, k.sq_ns / (double) k.n - m * m);
            std::fprintf(f, "%p,%zu,%lu,%zu,%s,%llu,%llu,%llu,%llu,%.3f,%.3f,%.3f\n", key, t.e.size(), t.measured, i,
                         k.name.c_str(), (unsigned long long) k.grid.width, (unsigned long long) k.grid.height,
                         (unsigned long long) k.grid.depth,
                         (unsigned long long) (k.block.width * k.block.height * k.block.depth), m / 1e3,
                         std::sqrt(v) / 1e3, k.gap_ns / (double) k.n / 1e3);
        }
    }
    std::fclose(f);
    std::rename(tmp.c_str(), kprofile_path());
    for (const auto& [key, t] : g_ktapes)
        if (t.measured > 0)
            std::fprintf(stderr, "metal kprofile: tape %p entries=%zu measured=%lu span %.3f ms busy %.3f ms\n", key,
                         t.e.size(), t.measured, t.span_ns / (double) t.measured / 1e6,
                         t.busy_ns / (double) t.measured / 1e6);
}

// Direct launches (the prompt path is not captured): one sampled pass per launch in the open command buffer;
// per kernel name and grid, summed. A command buffer holds at most 2048 sampled passes - past that it is
// committed early (diagnostic only). Copies and MPS work are not sampled.
struct KDirect { double sum_ns = 0, gap_ns = 0; unsigned long n = 0; };
std::map<std::string, KDirect> g_kdirect;
unsigned long g_kdirect_cbs = 0;

void kprofile_direct_write() {   // caller holds g_kmu
    const std::string path = std::string(kprofile_path()) + ".direct.csv", tmp = path + ".tmp";
    std::FILE* f = std::fopen(tmp.c_str(), "w");
    if (f == nullptr) return;
    std::fprintf(f, "kernel_grid_threads,count,total_ms,mean_us,gap_before_us\n");
    for (const auto& [key, k] : g_kdirect)
        std::fprintf(f, "%s,%lu,%.3f,%.3f,%.3f\n", key.c_str(), k.n, k.sum_ns / 1e6, k.sum_ns / (double) k.n / 1e3,
                     k.gap_ns / (double) k.n / 1e3);
    std::fclose(f);
    std::rename(tmp.c_str(), path.c_str());
}

void kprofile_direct_attach(Stream* s) {
    id<MTLCounterSampleBuffer> sb = s->kp_samples;
    std::vector<std::string>* names = s->kp_names;
    s->kp_samples = nil;
    s->kp_names = nullptr;
    [s->cur addCompletedHandler:^(id<MTLCommandBuffer>) {
        const size_t n = names->size();
        NSData* data = n ? [sb resolveCounterRange:NSMakeRange(0, 2 * n)] : nil;
        if (data != nil && data.length >= 2 * n * sizeof(MTLCounterResultTimestamp)) {
            const MTLCounterResultTimestamp* r = (const MTLCounterResultTimestamp*) data.bytes;
            std::lock_guard<std::mutex> lock(g_kmu);
            for (size_t i = 0; i < n; ++i) {
                if (r[2 * i].timestamp == MTLCounterErrorValue || r[2 * i + 1].timestamp == MTLCounterErrorValue) continue;
                KDirect& k = g_kdirect[(*names)[i]];
                k.sum_ns += std::max(0.0, (double) r[2 * i + 1].timestamp - (double) r[2 * i].timestamp);
                if (i > 0 && r[2 * i - 1].timestamp != MTLCounterErrorValue)
                    k.gap_ns += std::max(0.0, (double) r[2 * i].timestamp - (double) r[2 * i - 1].timestamp);
                ++k.n;
            }
            if (++g_kdirect_cbs % 32 == 0) kprofile_direct_write();
        }
        [sb release];
        delete names;
    }];
}

/// One direct launch under STRATA_METAL_KPROFILE: its own sampled compute pass.
void kprofile_direct_encode(Stream* s, const TapeEntry& e, const char* name) {
    static id<MTLCounterSet> timestamps = [] {
        for (id<MTLCounterSet> cs in g_device.counterSets)
            if ([cs.name isEqualToString:MTLCommonCounterSetTimestamp]) return [cs retain];
        return (id<MTLCounterSet>) nil;
    }();
    constexpr size_t kCap = 2048;
    end_compute(s);
    if (s->kp_names != nullptr && s->kp_names->size() >= kCap) commit_current(s);
    id<MTLCommandBuffer> cb = ensure_cb(s);
    if (s->kp_samples == nil && timestamps != nil) {
        MTLCounterSampleBufferDescriptor* d = [[MTLCounterSampleBufferDescriptor new] autorelease];
        d.counterSet = timestamps;
        d.storageMode = MTLStorageModeShared;
        d.sampleCount = 2 * kCap;
        NSError* err = nil;
        s->kp_samples = [g_device newCounterSampleBufferWithDescriptor:d error:&err];
        s->kp_names = new std::vector<std::string>();
    }
    MTLComputePassDescriptor* pd = [MTLComputePassDescriptor computePassDescriptor];
    pd.dispatchType = MTLDispatchTypeSerial;
    if (s->kp_samples != nil) {
        const NSUInteger at = NSUInteger(2 * s->kp_names->size());
        pd.sampleBufferAttachments[0].sampleBuffer = s->kp_samples;
        pd.sampleBufferAttachments[0].startOfEncoderSampleIndex = at;
        pd.sampleBufferAttachments[0].endOfEncoderSampleIndex = at + 1;
        char key[256];
        std::snprintf(key, sizeof key, "%s %llux%llux%llu %llu", name, (unsigned long long) e.grid.width,
                      (unsigned long long) e.grid.height, (unsigned long long) e.grid.depth,
                      (unsigned long long) (e.block.width * e.block.height * e.block.depth));
        s->kp_names->push_back(key);
    }
    id<MTLComputeCommandEncoder> enc = [cb computeCommandEncoderWithDescriptor:pd];
    encode_entry(enc, e);
    [enc endEncoding];
}

/// One profiled replay: each entry in its own sampled pass inside the stream's open command buffer.
void kprofile_launch(Stream* s, const void* key, const Tape& tape) {
    static const unsigned long skip = [] {
        const char* v = std::getenv("STRATA_METAL_KPROFILE_SKIP");
        return v ? std::strtoul(v, nullptr, 10) : 8ul;
    }();
    static id<MTLCounterSet> timestamps = [] {
        for (id<MTLCounterSet> cs in g_device.counterSets)
            if ([cs.name isEqualToString:MTLCommonCounterSetTimestamp]) return [cs retain];   // outlives the pool
        return (id<MTLCounterSet>) nil;
    }();
    const size_t n = tape.entries.size();
    bool measure = false;
    {
        std::lock_guard<std::mutex> lock(g_kmu);
        KTape& t = g_ktapes[key];
        if (t.e.size() != n) {
            t = KTape{};
            t.e.resize(n);
            for (size_t i = 0; i < n; ++i) {
                const TapeEntry& e = tape.entries[i];
                KStat& k = t.e[i];
                if (e.is_copy) {
                    k.name = compute_copy_fits(e.copy_bytes) ? "copy(compute)" : "copy(blit)";
                    k.grid = MTLSizeMake(e.copy_bytes, 1, 1);
                } else {
                    const auto it = g_pso_names.find((const void*) e.pso);
                    k.name = it != g_pso_names.end() ? it->second : "?";
                    k.grid = e.grid;
                    k.block = e.block;
                }
            }
        }
        measure = t.launches++ >= skip;
    }
    end_compute(s);
    id<MTLCommandBuffer> cb = ensure_cb(s);
    constexpr size_t kChunk = 2048;                      // 2 samples per entry; 4096 samples is the cap here
    std::vector<id<MTLCounterSampleBuffer>> bufs;
    for (size_t base = 0; base < n; base += kChunk) {
        id<MTLCounterSampleBuffer> sb = nil;
        if (measure && timestamps != nil) {
            MTLCounterSampleBufferDescriptor* d = [[MTLCounterSampleBufferDescriptor new] autorelease];
            d.counterSet = timestamps;
            d.storageMode = MTLStorageModeShared;
            d.sampleCount = 2 * std::min(kChunk, n - base);
            NSError* err = nil;
            sb = [g_device newCounterSampleBufferWithDescriptor:d error:&err];
        }
        if (sb == nil) measure = false;
        bufs.push_back(sb);
        for (size_t i = base; i < std::min(n, base + kChunk); ++i) {
            const TapeEntry& e = tape.entries[i];
            const NSUInteger at = NSUInteger(2 * (i - base));
            const bool blit = e.is_copy && !compute_copy_fits(e.copy_bytes);
            if (blit) {
                MTLBlitPassDescriptor* pd = [MTLBlitPassDescriptor blitPassDescriptor];
                if (sb != nil) {
                    pd.sampleBufferAttachments[0].sampleBuffer = sb;
                    pd.sampleBufferAttachments[0].startOfEncoderSampleIndex = at;
                    pd.sampleBufferAttachments[0].endOfEncoderSampleIndex = at + 1;
                }
                id<MTLBlitCommandEncoder> b = [cb blitCommandEncoderWithDescriptor:pd];
                if (e.copy_bytes > 0)
                    [b copyFromBuffer:e.copy_src sourceOffset:e.copy_src_off toBuffer:e.copy_dst
                        destinationOffset:e.copy_dst_off size:e.copy_bytes];
                [b endEncoding];
                continue;
            }
            MTLComputePassDescriptor* pd = [MTLComputePassDescriptor computePassDescriptor];
            pd.dispatchType = MTLDispatchTypeSerial;
            if (sb != nil) {
                pd.sampleBufferAttachments[0].sampleBuffer = sb;
                pd.sampleBufferAttachments[0].startOfEncoderSampleIndex = at;
                pd.sampleBufferAttachments[0].endOfEncoderSampleIndex = at + 1;
            }
            id<MTLComputeCommandEncoder> enc = [cb computeCommandEncoderWithDescriptor:pd];
            if (e.is_copy) {
                if (e.copy_bytes > 0)
                    encode_compute_copy(enc, e.copy_dst, e.copy_dst_off, e.copy_src, e.copy_src_off, e.copy_bytes);
            } else {
                encode_entry(enc, e);
            }
            [enc endEncoding];
        }
    }
    if (!measure) {
        for (id<MTLCounterSampleBuffer> b : bufs) [b release];
        return;
    }
    [cb addCompletedHandler:^(id<MTLCommandBuffer>) {
        std::vector<double> t0(n, 0.0), t1(n, 0.0);
        bool ok = true;
        for (size_t c = 0; c < bufs.size(); ++c) {
            const size_t base = c * kChunk, m = std::min(kChunk, n - base);
            NSData* data = [bufs[c] resolveCounterRange:NSMakeRange(0, 2 * m)];
            if (data == nil || data.length < 2 * m * sizeof(MTLCounterResultTimestamp)) { ok = false; continue; }
            const MTLCounterResultTimestamp* r = (const MTLCounterResultTimestamp*) data.bytes;
            for (size_t i = 0; i < m; ++i) {
                if (r[2 * i].timestamp == MTLCounterErrorValue || r[2 * i + 1].timestamp == MTLCounterErrorValue)
                    ok = false;
                t0[base + i] = (double) r[2 * i].timestamp;
                t1[base + i] = (double) r[2 * i + 1].timestamp;
            }
        }
        for (id<MTLCounterSampleBuffer> b : bufs) [b release];
        if (!ok || n == 0) return;
        std::lock_guard<std::mutex> lock(g_kmu);
        KTape& t = g_ktapes[key];
        if (t.e.size() != n) return;
        double busy = 0;
        for (size_t i = 0; i < n; ++i) {
            const double d = std::max(0.0, t1[i] - t0[i]);
            KStat& k = t.e[i];
            k.sum_ns += d;
            k.sq_ns += d * d;
            k.gap_ns += i > 0 ? std::max(0.0, t0[i] - t1[i - 1]) : 0.0;
            ++k.n;
            busy += d;
        }
        t.busy_ns += busy;
        t.span_ns += std::max(0.0, t1[n - 1] - t0[0]);
        if (++t.measured % 16 == 0) kprofile_write();
    }];
}

