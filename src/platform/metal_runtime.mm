cudaError_t cudaMalloc(void** ptr, size_t bytes) {
    ensure_boot();
    if (bytes == 0) { *ptr = nullptr; return cudaSuccess; }
    @autoreleasepool {
        id<MTLBuffer> b = [g_device newBufferWithLength:bytes options:MTLResourceStorageModeShared];
        if (b == nil) return fail(cudaErrorMemoryAllocation);
        std::lock_guard<std::mutex> lock(g_mu);
        g_ranges[b.contents] = { b.contents, bytes, b };
        *ptr = b.contents;
    }
    return cudaSuccess;
}

cudaError_t cudaFree(void* ptr) {
    if (ptr == nullptr) return cudaSuccess;
    std::lock_guard<std::mutex> lock(g_mu);
    const auto it = g_ranges.find(ptr);
    if (it == g_ranges.end()) return fail(cudaErrorInvalidValue);
    if (it->second.buffer != nil) [it->second.buffer release];
    g_ranges.erase(it);
    return cudaSuccess;
}

static cudaError_t host_alloc(void** ptr, size_t bytes, bool page_align) {
    ensure_boot();
    (void) page_align;
    const size_t allocated = ((std::max(bytes, size_t(1)) + 16383) / 16384) * 16384;
    void* p = std::aligned_alloc(16384, allocated);
    if (p == nullptr) return fail(cudaErrorMemoryAllocation);
    std::memset(p, 0, bytes);
    @autoreleasepool {
        id<MTLBuffer> b = [g_device newBufferWithBytesNoCopy:p length:allocated
                                                    options:MTLResourceStorageModeShared deallocator:nil];
        if (b == nil) {                                 // still usable as host memory; the GPU just cannot see it
            std::fprintf(stderr, "strata-metal: cudaHostAlloc: no-copy wrap failed (%zu B)\n", bytes);
        }
        std::lock_guard<std::mutex> lock(g_mu);
        g_ranges[p] = { p, bytes, b };
    }
    *ptr = p;
    return cudaSuccess;
}

cudaError_t cudaMallocHost(void** ptr, size_t bytes) { return host_alloc(ptr, bytes, false); }
cudaError_t cudaHostAlloc(void** ptr, size_t bytes, unsigned) { return host_alloc(ptr, bytes, true); }

cudaError_t cudaFreeHost(void* ptr) {
    if (ptr == nullptr) return cudaSuccess;
    std::lock_guard<std::mutex> lock(g_mu);
    const auto it = g_ranges.find(ptr);
    const bool known = it != g_ranges.end();
    if (known) {
        if (it->second.buffer != nil) [it->second.buffer release];
        g_ranges.erase(it);
    }
    std::free(ptr);                                    // the MTLBuffer wraps it no-copy; nothing else to free
    return known ? cudaSuccess : fail(cudaErrorInvalidValue);
}

cudaError_t cudaHostRegister(void* ptr, size_t bytes, unsigned) {
    ensure_boot();
    // page-aligned no-copy wrap; a non-page-aligned arena is refused (pinned.cu's fallback paths handle it)
    if (((uintptr_t) ptr % 16384) != 0 || (bytes % 64) != 0) return fail(cudaErrorInvalidValue);
    @autoreleasepool {
        id<MTLBuffer> b = [g_device newBufferWithBytesNoCopy:ptr length:bytes
                                                    options:MTLResourceStorageModeShared deallocator:nil];
        if (b == nil) return fail(cudaErrorInvalidValue);
        std::lock_guard<std::mutex> lock(g_mu);
        g_ranges[ptr] = { ptr, bytes, b };
    }
    return cudaSuccess;
}

cudaError_t cudaHostUnregister(void* ptr) {
    std::lock_guard<std::mutex> lock(g_mu);
    const auto it = g_ranges.find(ptr);
    if (it != g_ranges.end()) {
        if (it->second.buffer != nil) [it->second.buffer release];
        g_ranges.erase(it);                            // the host memory itself stays (it was the caller's)
    }
    return cudaSuccess;
}

cudaError_t cudaHostGetDevicePointer(void** device_ptr, const void* host_ptr, unsigned) {
    *device_ptr = const_cast<void*>(host_ptr);         // unified memory: the same address
    return cudaSuccess;
}

// A copy between runtime buffers runs on the stream as a blit (ordered, hazard-tracked).  A host pointer the
// runtime does not know (a test fixture's std::vector, a stack array) falls back to drain-then-memcpy, which
// is safe for the same stream and is all such callers need.
static cudaError_t copy_on_stream(void* dst, const void* src, size_t bytes, cudaStream_t stream, bool sync) {
    ensure_boot();
    Stream* s = strata::metal::as_stream(stream);
    @autoreleasepool {
        id<MTLBuffer> db = nil, sb = nil;
        NSUInteger doff = 0, soff = 0;
        bool dst_known = strata::metal::resolve(dst, &db, &doff);
        bool src_known = strata::metal::resolve(src, &sb, &soff);
        bool staged = false;
        if (dst_known && db != nil && !src_known) {
            // H2D from memory the runtime does not own (a test fixture's vector): stage it into a buffer the
            // GPU reads through a blit - a bare CPU memcpy is NOT guaranteed GPU-visible (measured, M1)
            if (std::getenv("STRATA_METAL_DEBUG")) {
                std::fprintf(stderr, "staging H2D %zu B from %p\n", bytes, src);
                strata::metal::dump_ranges("before staging");
            }
            sb = [g_device newBufferWithBytes:src length:bytes options:MTLResourceStorageModeShared];
            if (sb == nil) return fail(cudaErrorMemoryAllocation);
            staged = true;
            if (std::getenv("STRATA_METAL_DEBUG")) std::fprintf(stderr, "  staged -> %p\n", (void*) sb);
            soff = 0;
            src_known = true;
        }
        if (std::getenv("STRATA_METAL_DEBUG"))
            std::fprintf(stderr, "copy %p <- %p %zu B: dst_known=%d src_known=%d\n", dst, src, bytes,
                         (int) dst_known, (int) src_known);
        if (dst_known && src_known && db != nil && sb != nil) {
            if (s->capturing != nullptr) {
                strata::metal::TapeEntry e;
                e.is_copy = true;
                [db retain]; [sb retain];
                e.copy_dst = db; e.copy_dst_off = doff;
                e.copy_src = sb; e.copy_src_off = soff;
                e.copy_bytes = NSUInteger(bytes);
                s->capturing->entries.push_back(std::move(e));
                if (staged) [sb release];
                return cudaSuccess;                   // a captured async copy runs at replay
            }
            encode_copy_on(s, db, doff, sb, soff, NSUInteger(bytes));
            if (staged) [sb release];  // the command buffer retains the encoded resource
            if (sync) drain(s);
            return cudaSuccess;
        }
        // D2H into unowned memory: the source's GPU work is drained first, then the CPU reads (visible)
        drain(s);
        std::memcpy(dst, src, bytes);
        return cudaSuccess;
    }
}

cudaError_t cudaMemcpy(void* dst, const void* src, size_t bytes, cudaMemcpyKind) {
    // A synchronous legacy-stream copy observes previous work on blocking streams. Keeping this
    // ordering here lets data-producing kernels stay asynchronous instead of each forcing a wait.
    ensure_boot();
    std::vector<Stream*> streams;
    { std::lock_guard<std::mutex> lock(g_mu); streams = g_streams; }
    for (Stream* s : streams) if (!s->nonblocking && !s->capturing) commit_current(s);
    for (Stream* s : streams) if (!s->nonblocking && !s->capturing) drain(s);
    return copy_on_stream(dst, src, bytes, nullptr, true);
}

cudaError_t cudaMemcpyAsync(void* dst, const void* src, size_t bytes, cudaMemcpyKind, cudaStream_t stream) {
    return copy_on_stream(dst, src, bytes, stream, false);
}

cudaError_t cudaMemcpy2DAsync(void* dst, size_t dpitch, const void* src, size_t spitch,
                            size_t width, size_t count, cudaMemcpyKind kind, cudaStream_t stream) {
    if (width == 0 || count == 0) return cudaSuccess;
    if (width > dpitch || width > spitch) return fail(cudaErrorInvalidValue);
    ensure_boot();
    id<MTLBuffer> db = nil, sb = nil;
    NSUInteger doff = 0, soff = 0;
    if (strata::metal::compute_copies() && strata::metal::resolve(dst, &db, &doff) && db != nil &&
        strata::metal::resolve(src, &sb, &soff) && sb != nil) {
        const bool vector = ((doff | soff | dpitch | spitch | width) & 15) == 0;
        const unsigned long unit = vector ? 16 : 1, w = width / unit;
        const unsigned long dp = dpitch / unit, sp = spitch / unit;
        const unsigned threads = w <= 32 ? 32 : 128;
        strata::metal::Launch k(vector ? "runtime_copy2d16" : "runtime_copy2d1",
                               (unsigned) ((w + threads - 1) / threads), (unsigned) count, 1,
                               threads, 1, 1, 0, stream);
        k.buf(dst).buf(src).scalar(dp).scalar(sp).scalar(w); k.done();
        return cudaSuccess;
    }
    // Unregistered host memory keeps the staging/drain semantics of the one-dimensional API.
    for (size_t row = 0; row < count; ++row) {
        const auto e = copy_on_stream((char*) dst + row * dpitch, (const char*) src + row * spitch,
                                      width, stream, false);
        if (e != cudaSuccess) return e;
    }
    return cudaSuccess;
}

