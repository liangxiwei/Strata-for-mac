// ---- streams & events ----
cudaError_t cudaStreamCreate(cudaStream_t* stream) { return cudaStreamCreateWithFlags(stream, 0); }

cudaError_t cudaStreamCreateWithFlags(cudaStream_t* stream, unsigned flags) {
    ensure_boot();
    if (g_device == nil) return fail(cudaErrorInvalidValue);
    Stream* s = new Stream;
    s->nonblocking = (flags & cudaStreamNonBlocking) != 0;
    s->queue = [g_device newCommandQueue];
    s->callbacks = dispatch_queue_create("strata.stream", DISPATCH_QUEUE_SERIAL);
    std::lock_guard<std::mutex> lock(g_mu);
    g_streams.push_back(s);
    *stream = s;
    return cudaSuccess;
}

cudaError_t cudaStreamDestroy(cudaStream_t stream) {
    Stream* s = strata::metal::as_stream(stream);
    drain(s);
    dispatch_sync(s->callbacks, ^{});
    [s->inflight release];
    [s->queue release];
    dispatch_release(s->callbacks);
    std::lock_guard<std::mutex> lock(g_mu);
    g_streams.erase(std::remove(g_streams.begin(), g_streams.end(), s), g_streams.end());
    delete s;
    return cudaSuccess;
}

cudaError_t cudaStreamSynchronize(cudaStream_t stream) {
    ensure_boot();
    Stream* s = strata::metal::as_stream(stream);
    if (s->capturing) return cudaSuccess;
    strata::metal::drain(s);
    return cudaSuccess;
}

cudaError_t cudaStreamQuery(cudaStream_t stream) {
    Stream* s = strata::metal::as_stream(stream);
    if (s->cur != nil) return cudaErrorNotReady;
    if (s->inflight != nil) {
        // M6's first real token run caught the lie: a query right after a commit said "finished" while the
        // GPU was still executing and the engine read a ring that had not run - NotReady until it completes
        if ([s->inflight status] < MTLCommandBufferStatusCompleted) return cudaErrorNotReady;
        [s->inflight release];
        s->inflight = nil;
    }
    return cudaSuccess;
}

cudaError_t cudaStreamWaitEvent(cudaStream_t stream, cudaEvent_t event, unsigned) {
    Event* e = (Event*) event;
    [e->buffer waitUntilCompleted];
    (void) stream;
    return cudaSuccess;
}

cudaError_t cudaStreamIsCapturing(cudaStream_t stream, cudaStreamCaptureStatus* status) {
    Stream* s = strata::metal::as_stream(stream);
    *status = s->capturing ? cudaStreamCaptureStatusActive : cudaStreamCaptureStatusNone;
    return cudaSuccess;
}

