cudaError_t cudaGraphDestroy(cudaGraph_t graph) {
    Tape* tape = (Tape*) graph;
    for (const strata::metal::TapeEntry& e : tape->entries)
        if (e.is_copy) { [e.copy_dst release]; [e.copy_src release]; }
        // kernels' PSOs are NOT released here: the pso cache owns them for the process lifetime
    delete tape;
    return cudaSuccess;
}

