cudaError_t cudaEventCreateWithFlags(cudaEvent_t* event, unsigned) {
    *event = new Event;
    return cudaSuccess;
}

cudaError_t cudaEventDestroy(cudaEvent_t event) {
    delete (Event*) event;
    return cudaSuccess;
}

cudaError_t cudaEventRecord(cudaEvent_t event, cudaStream_t stream) {
    ensure_boot();
    Stream* s = strata::metal::as_stream(stream);
    Event* e = (Event*) event;
    if (s->capturing) return cudaSuccess;              // an event inside a capture: the replay below rings it
    commit_current(s);
    [s->inflight retain];
    [e->buffer release];
    e->buffer = s->inflight;
    e->at_ns = now_ns();
    return cudaSuccess;
}

cudaError_t cudaEventQuery(cudaEvent_t event) {
    Event* e = (Event*) event;
    // Query the driver, not a callback-thread flag: this also makes shared-buffer writes visible.
    return e->buffer == nil || e->buffer.status >= MTLCommandBufferStatusCompleted
        ? cudaSuccess : cudaErrorNotReady;
}

cudaError_t cudaEventSynchronize(cudaEvent_t event) {
    Event* e = (Event*) event;
    [e->buffer waitUntilCompleted];
    return cudaSuccess;
}

cudaError_t cudaEventElapsedTime(float* ms, cudaEvent_t start, cudaEvent_t end) {
    Event* a = (Event*) start, * b = (Event*) end;
    if (cudaEventQuery(start) != cudaSuccess || cudaEventQuery(end) != cudaSuccess) return cudaErrorNotReady;
    const double ag = a->buffer.GPUEndTime, bg = b->buffer.GPUEndTime;
    // Empty streams have no GPU timestamp. Never subtract timestamps from different clocks.
    *ms = ag > 0 && bg > 0 ? float((bg - ag) * 1e3) : float((double(b->at_ns) - double(a->at_ns)) / 1e6);
    return cudaSuccess;
}

cudaError_t cudaLaunchHostFunc(cudaStream_t stream, void (*fn)(void*), void* user) {
    Stream* s = strata::metal::as_stream(stream);
    if (s->capturing) return fail(cudaErrorStreamCaptureUnsupported);
    ensure_cb(s);
    commit_current(s);
    id<MTLCommandBuffer> cb = s->inflight;
    dispatch_async(s->callbacks, ^{
        [cb waitUntilCompleted];
        fn(user);
    });
    return cudaSuccess;
}

// ---- graphs: the tape --------------------------------------------------------------------
cudaError_t cudaStreamBeginCapture(cudaStream_t stream, int) {
    Stream* s = strata::metal::as_stream(stream);
    if (s->capturing) return fail(cudaErrorStreamCaptureUnsupported);
    commit_current(s);
    s->capturing = new Tape;
    return cudaSuccess;
}

cudaError_t cudaStreamEndCapture(cudaStream_t stream, cudaGraph_t* graph) {
    Stream* s = strata::metal::as_stream(stream);
    if (s->capturing == nullptr) { *graph = nullptr; return fail(cudaErrorStreamCaptureUnsupported); }
    *graph = s->capturing;
    s->capturing = nullptr;
    return cudaSuccess;
}

cudaError_t cudaGraphInstantiate(cudaGraphExec_t* exec, cudaGraph_t graph, void*, void*, unsigned long long) {
    // CUDA permits destroying the source graph immediately after instantiation (MTP does so).
    Tape* copy = new Tape(*(Tape*) graph);
    for (const auto& e : copy->entries)
        if (e.is_copy) { [e.copy_dst retain]; [e.copy_src retain]; }
    *exec = copy;
    return cudaSuccess;
}

cudaError_t cudaGraphLaunch(cudaGraphExec_t exec, cudaStream_t stream) {
    @autoreleasepool {
    Stream* s = strata::metal::as_stream(stream);
    Tape* tape = (Tape*) exec;
    static const bool time_encoding = std::getenv("STRATA_METAL_GRAPH_TIMING") != nullptr;
    const double encode_start = time_encoding ? strata::metal::now_ns() : 0;
    if (strata::metal::kprofile_path() != nullptr && s->capturing == nullptr) {
        strata::metal::kprofile_launch(s, exec, *tape);
        return cudaSuccess;
    }
    for (const strata::metal::TapeEntry& e : tape->entries) {
        if (e.is_copy) {
            encode_copy_on(s, e.copy_dst, e.copy_dst_off, e.copy_src, e.copy_src_off, e.copy_bytes);
        } else {
            id<MTLComputeCommandEncoder> enc = strata::metal::ensure_compute(s);
            strata::metal::encode_entry(enc, e);
            if (strata::metal::encoder_per_kernel()) strata::metal::end_compute(s);
        }
    }
    if (time_encoding) {
        static std::atomic<int> index{0};
        if (index.fetch_add(1) < 32)
            std::fprintf(stderr, "metal graph: entries=%zu encode_ms=%.3f\n", tape->entries.size(),
                         (strata::metal::now_ns() - encode_start) / 1e6);
    }
    return cudaSuccess;
    }
}

cudaError_t cudaGraphUpload(cudaGraphExec_t, cudaStream_t) { return cudaSuccess; }

cudaError_t cudaGraphGetNodes(cudaGraph_t graph, cudaGraphNode_t* nodes, size_t* count) {
    Tape* tape = (Tape*) graph;
    *count = tape->entries.size();
    if (nodes != nullptr)
        for (size_t i = 0; i < tape->entries.size(); ++i) nodes[i] = (cudaGraphNode_t) (i + 1);
    return cudaSuccess;
}

