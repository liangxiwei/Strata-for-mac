// ---- the launcher builder ---------------------------------------------------------------
struct Launch::Impl {
    const char* name;
    id<MTLComputePipelineState> pipeline;
    MTLSize grid, block;
    NSUInteger shared_bytes;
    Stream* stream;
    TapeEntry entry;                                   // filled by buf()/scalar(); encoded at done()
};

Launch::Launch(const char* kernel, unsigned gx, unsigned gy, unsigned gz, unsigned bx, unsigned by, unsigned bz,
               size_t shared_bytes, void* stream)
    : impl_(new Impl) {
    impl_->name = kernel;
    impl_->pipeline = pso(kernel);
    [impl_->pipeline retain];
    impl_->grid = MTLSizeMake(gx, gy, gz);
    impl_->block = MTLSizeMake(bx, by, bz);
    impl_->shared_bytes = NSUInteger(shared_bytes);
    impl_->stream = as_stream((cudaStream_t) stream);
    impl_->entry.pso = impl_->pipeline;                // Impl owns one retain; the entry shares it
    impl_->entry.grid = impl_->grid;
    impl_->entry.block = impl_->block;
    impl_->entry.shared_bytes = NSUInteger(shared_bytes);
}

Launch::~Launch() {
    [impl_->pipeline release];
    delete impl_;
}

Launch& Launch::buf(const void* ptr) {
    TapeEntry::Arg a;
    if (ptr == nullptr) {                               // CUDA kernels test their pointers: pass null
        a.is_null = true;                               // through as a null binding, not a dummy buffer
        impl_->entry.args.push_back(std::move(a));
        return *this;
    }
    id<MTLBuffer> buffer = nil;
    NSUInteger offset = 0;
    if (!resolve(ptr, &buffer, &offset)) {
        std::fprintf(stderr, "strata-metal: launch argument %p is not a runtime buffer\n", ptr);
        std::abort();
    }
    a.buffer = buffer;
    a.offset = offset;
    impl_->entry.args.push_back(std::move(a));
    return *this;
}

Launch& Launch::scalar(const void* p, size_t bytes) {
    TapeEntry::Arg a;
    a.bytes = NSUInteger(bytes);
    a.value.assign((const unsigned char*) p, (const unsigned char*) p + bytes);
    impl_->entry.args.push_back(std::move(a));
    return *this;
}

void Launch::done() {
    @autoreleasepool {
    Stream* s = impl_->stream;
    // RULE 10 (measured, gdn's port): a dispatch wider than the pipeline's occupancy limit is SILENTLY
    // DROPPED on this GPU - the command buffer completes clean and nothing runs (a register-heavy kernel
    // pinned to 384 threads took a 512-thread launch and wrote nothing, no error anywhere).  Refuse it
    // here, while the mistake still names its kernel.
    if (impl_->block.width * impl_->block.height * impl_->block.depth >
        impl_->pipeline.maxTotalThreadsPerThreadgroup) {
        std::fprintf(stderr, "strata-metal: launch of '%s' wants %llu threads but its pipeline allows %zu - "
                             "the dispatch would be dropped silently\n",
                     impl_->name, (unsigned long long) impl_->block.width,
                     (std::size_t) impl_->pipeline.maxTotalThreadsPerThreadgroup);
        std::abort();
    }
    if (s->capturing != nullptr) {
        s->capturing->entries.push_back(std::move(impl_->entry));
        return;
    }
    if (kprofile_path() != nullptr) {      // diagnostic: a sampled pass per launch (see kprofile_direct_encode)
        kprofile_direct_encode(s, impl_->entry, impl_->name);
        return;
    }
    id<MTLCommandBuffer> cb = ensure_cb(s);
    id<MTLComputeCommandEncoder> enc = cb != nil ? ensure_compute(s) : nil;
    if (debug_trace()) {
        std::fprintf(stderr, "done: %s stream=%p cb=%p enc=%p args:", impl_->name, (void*) s, (void*) cb,
                     (void*) enc);
        for (const auto& a : impl_->entry.args)
            std::fprintf(stderr, a.buffer != nil ? " buf%llu@%llu" : " val%zu",
                         a.buffer != nil ? (unsigned long long) a.buffer.length
                                         : (unsigned long long) a.offset,
                         a.buffer != nil ? (unsigned long long) a.offset : 0ull);
        std::fprintf(stderr, "\n");
    }
    if (enc == nil) return;
    encode_entry(enc, impl_->entry);
    if (encoder_per_kernel()) end_compute(s);
    if (debug_trace()) {
        std::fprintf(stderr, "launch: grid=%llu block=%llu args=%zu:",
                     (unsigned long long) impl_->entry.grid.width,
                     (unsigned long long) impl_->entry.block.width, impl_->entry.args.size());
        for (const auto& a : impl_->entry.args)
            std::fprintf(stderr, a.buffer != nil ? " buf+%zu" : " val%zu", a.buffer != nil ? a.offset : a.value.size());
        std::fprintf(stderr, "\n");
    }
    }
}

