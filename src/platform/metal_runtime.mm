// src/platform/metal_runtime.mm - the Metal backend's runtime (docs/PORT_METAL/).
//
// Implements the CUDA-runtime surface declared in include/strata/metal_compat/cuda_runtime.h and the launcher
// builder in include/strata/platform/metal_launch.hpp.  The design constraints, all inherited from the engine's
// existing shape (see PLAN.md):
//
//   * unified memory: every cudaMalloc is a shared-storage MTLBuffer whose bytes the CPU can also touch, so a
//     cudaMemcpy is a plain memcpy - AFTER ordering it against the stream's pending work (commit + wait);
//   * a stream is a serial chain of command buffers on one queue; the current buffer stays open across
//     launches and is committed at the sync points (stream sync, event record, memcpy);
//   * capture is a TAPE: launches append (pipeline, buffers, bytes, geometry); cudaGraphLaunch re-encodes.
//     Replays stay correct because the engine already relies only on persistent buffers with changing
//     contents - the doorbells carry the dynamics (elementwise.hpp's ring/wait/publish);
//   * an event retains its command buffer and queries/waits on its completion. GPU end timestamps are
//     used for elapsed time when both exist, otherwise both endpoints use host record timestamps.
