cudaError_t cudaMemsetAsync(void* ptr, int value, size_t bytes, cudaStream_t stream) {
    ensure_boot();
    Stream* s = strata::metal::as_stream(stream);
    id<MTLBuffer> b = nil;
    NSUInteger off = 0;
    if (strata::metal::resolve(ptr, &b, &off) && b != nil && s->capturing == nullptr) {
        strata::metal::Launch k("memset8_kernel", (unsigned) ((bytes + 255) / 256), 1, 1, 256, 1, 1, 0, (void*) s);
        k.buf(ptr);
        const unsigned char v = (unsigned char) value;
        const unsigned long n = (unsigned long) bytes;
        k.scalar(v).scalar(n);
        k.done();
        return cudaSuccess;
    }
    drain(s);
    std::memset(ptr, value, bytes);
    return cudaSuccess;
}

