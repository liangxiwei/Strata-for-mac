// ---- the MPS seam (M4, the prefill GEMM) - declared in metal_launch.hpp -------------------
// MPS encodes its own kernels; the three helpers below hand a ported .mm the same facts Launch uses
// internally, as opaque pointers so the header stays includable from plain C++.
void* mtl_command_buffer(void* stream) {
    ensure_boot();
    Stream* s = as_stream((cudaStream_t) stream);
    end_compute(s);                           // MPS opens its own encoders on this command buffer
    id<MTLCommandBuffer> cb = ensure_cb(s);      // the SAME open buffer Launch encodes into
    [cb retain];                                 // the caller releases it after encoding
    return (__bridge void*) cb;
}

bool resolve_buffer(const void* ptr, void** buffer, uint64_t* offset) {
    ensure_boot();
    id<MTLBuffer> b = nil;
    NSUInteger off = 0;
    if (!resolve(ptr, &b, &off) || b == nil) return false;
    [b retain];                                  // the caller releases it after encoding
    *buffer = (__bridge void*) b;
    *offset = (uint64_t) off;
    return true;
}

void* mtl_device() {
    ensure_boot();
    return (__bridge void*) g_device;            // borrowed: boot() retains it for the process
}

void poison(float* p, uint64_t n_floats) {
    // the same chunking device.cu uses for the CUDA kernel (gridDim.x is 32-bit there)
    const unsigned threads = 256;
    const uint64_t blocks = (n_floats + threads - 1) / threads;
    const uint64_t max_blocks = 0x7FFFFFFFull;
    for (uint64_t b = 0; b < blocks; b += max_blocks) {
        const uint64_t chunk = (blocks - b < max_blocks) ? blocks - b : max_blocks;
        Launch k("poison_kernel", (unsigned) chunk, 1, 1, threads, 1, 1, 0, nullptr);
        k.buf(p + b * threads);
        k.done();
    }
    cudaDeviceSynchronize();
}

